import type { CostType, QuotationDraft, QuotationItem, QuotationSection } from "../domain/models";

function item(
  id: string,
  itemNumber: string,
  description: string,
  quantity: string,
  unit: string,
  costType: CostType,
  materialUnitCost: string,
  laborUnitCost: string,
): QuotationItem {
  return {
    id,
    rowType: "item",
    itemNumber,
    description,
    quantity,
    unit,
    costType,
    materialUnitCost,
    laborUnitCost,
    otherUnitCost: "0",
    sortOrder: Number(itemNumber) || 0,
  };
}

function heading(id: string, description: string, sortOrder: number): QuotationItem {
  return {
    id,
    rowType: "heading",
    itemNumber: "",
    description,
    quantity: "0",
    unit: "",
    costType: "MATERIAL",
    materialUnitCost: "0",
    laborUnitCost: "0",
    otherUnitCost: "0",
    sortOrder,
  };
}

function section(id: string, sectionNumber: string, name: string, items: QuotationItem[], sortOrder: number): QuotationSection {
  return { id, sectionNumber, name, sortOrder, items };
}

